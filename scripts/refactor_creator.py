def main():
    rows = json.load(open(os.path.join(BASE, "dataset_lingjing.json"), encoding="utf-8"))
    out_rows, report = [], []
    for r in rows:
        sid = r["metadata"]["segment_id"]
        o = OUTLINES[sid]
        text = r["output"]
        # 正向核对: input 的信息点是否都能在 output 找到
        miss = [c for c in o["checks"] if c not in text]
        # 反向核对: 关键转折是否已写进 input
        rev = [t for t in o["turnings"] if not any(k in o["input"] for k in t.replace("、", "")[:0] or [t])]
        out_rows.append({
            "instruction": INSTRUCTION,
            "input": o["input"],
            "output": text,
            "metadata": {
                "segment_id": sid,
                "source_position": r["metadata"]["source_position"],
            },
        })
        report.append({
            "segment_id": sid,
            "source_position": r["metadata"]["source_position"],
            "input_chars": len(o["input"]),
            "info_points": len(o["checks"]),
            "missing": miss,
            "turnings": o["turnings"],
            "passed": len(miss) == 0,
        })

    json.dump(out_rows, open(os.path.join(BASE, "dataset_lingjing_creator.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    with open(os.path.join(BASE, "dataset_lingjing.jsonl"), "w", encoding="utf-8") as f:
        for r in out_rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    json.dump(report, open(os.path.join(BASE, "meta", "input核对表.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)

    print("重构条数:", len(out_rows))
    L = [x["input_chars"] for x in report]
    print(f"input 长度: min={min(L)} max={max(L)} mean={sum(L)/len(L):.0f}  (要求 50-150)")
    okc = sum(1 for x in report if x["passed"])
    print(f"信息点核对通过: {okc}/{len(report)}")
    for x in report:
        flag = "OK " if x["passed"] else "缺:"
        print(f"  {x['segment_id']}  {x['input_chars']}字  {x['info_points']}点  {flag}{','.join(x['missing'])}")


if __name__ == "__main__":
    main()
