def pick(sid):
    return int(hashlib.md5(sid.encode('utf-8')).hexdigest(), 16) % len(LEAD)


def main():
    scenes = json.load(open(SCENES, encoding='utf-8'))
    rows = [json.loads(l) for l in open(OUT, encoding='utf-8')] if os.path.exists(OUT) else []
    have = {r['metadata']['scene_id'] for r in rows}
    added = 0
    for s in scenes:
        sid = s['scene_id']
        if sid not in SKEL or sid in have:
            continue
        sk = SKEL[sid]
        rows.append({"instruction": f"{LEAD[pick(sid)]}要求：{STYLE}{HARD}", "input": sk, "output": s['text'],
                     "metadata": {"scene_id": sid, "chapter": s['chapter'], "chapter_title": s['chapter_title'],
                                  "skeleton_len": len(sk), "scene_char": s['char_count']}})
        added += 1
    with open(OUT, 'w', encoding='utf-8') as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + '\n')
    print(f'批次3 新增 {added} 条，数据集共 {len(rows)} 条')
    left = [s['scene_id'] for s in scenes if s['scene_id'] not in SKEL]
    print(f'批次3 剩余待写: {len(left)} 个')


if __name__ == '__main__':
    main()
