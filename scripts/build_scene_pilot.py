def pick(sid):
    return int(hashlib.md5(sid.encode('utf-8')).hexdigest(), 16) % len(LEAD)


def main():
    scenes = json.load(open(SCENES, encoding='utf-8'))
    rows, miss = [], []
    for s in scenes:
        sid = s['scene_id']
        if sid not in SKEL:
            miss.append(sid)
            continue
        sk = SKEL[sid]
        ins = f"{LEAD[pick(sid)]}要求：{STYLE}{HARD}"
        rows.append({"instruction": ins, "input": sk, "output": s['text'],
                     "metadata": {"scene_id": sid, "chapter": s['chapter'],
                                  "chapter_title": s['chapter_title'],
                                  "skeleton_len": len(sk), "scene_char": s['char_count']}})
    with open(OUT, 'w', encoding='utf-8') as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + '\n')
    S = sorted(r['metadata']['skeleton_len'] for r in rows)
    O = sorted(r['metadata']['scene_char'] for r in rows)
    print(f'已写出 {OUT}（{len(rows)} 条）')
    print(f'骨架长度: min {S[0]} / p50 {S[len(S)//2]} / max {S[-1]}')
    print(f'场景长度: min {O[0]} / p50 {O[len(O)//2]} / max {O[-1]}')
    print(f'未写骨架: {len(miss)} 个 {miss[:8]}')


if __name__ == '__main__':
    main()
